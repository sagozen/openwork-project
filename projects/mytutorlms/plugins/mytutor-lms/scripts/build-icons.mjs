#!/usr/bin/env node
// Regenerates src/design/icons.ts from an unpacked lucide-static package.
//
//   npm pack lucide-static@1.52.0 && tar xzf lucide-static-1.52.0.tgz
//   node scripts/build-icons.mjs package
//
// Only the subset below ships. Add a name here, rerun, and commit the result.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const NAMES = [
  "arrow-left",
  "arrow-right",
  "arrow-up-right",
  "award",
  "calendar",
  "captions",
  "check",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "circle-alert",
  "circle-check",
  "clock",
  "copy",
  "credit-card",
  "external-link",
  "file",
  "funnel",
  "globe",
  "info",
  "layout-grid",
  "list",
  "lock",
  "log-out",
  "menu",
  "message-circle",
  "monitor",
  "moon",
  "pause",
  "play",
  "qr-code",
  "search",
  "settings",
  "sparkles",
  "sun",
  "triangle-alert",
  "trophy",
  "upload",
  "user",
  "x",
];

const dir = process.argv[2];
if (!dir) {
  console.error(
    "Usage: node scripts/build-icons.mjs <unpacked lucide-static dir>",
  );
  process.exit(1);
}
const version = JSON.parse(
  readFileSync(join(dir, "package.json"), "utf8"),
).version;
const entries = NAMES.map((name) => {
  const svg = readFileSync(join(dir, "icons", `${name}.svg`), "utf8");
  const body = svg
    .slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .replace(/\s*\n\s*/g, "")
    .replace(/\s+\/>/g, "/>");
  return `  "${name}": ${JSON.stringify(body)},`;
});
writeFileSync(
  new URL("../src/design/icons.ts", import.meta.url),
  `// Generated by scripts/build-icons.mjs from lucide-static ${version} (ISC
// License, Copyright (c) Lucide Icons and Contributors). Do not edit by hand.
export const ICONS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof ICONS;
`,
);
console.log(`Wrote ${NAMES.length} icons from lucide-static ${version}.`);
