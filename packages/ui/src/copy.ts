export type MessageKey = keyof typeof messages.en;

const PSEUDO_MAP: Record<string, string> = {
  a: "á",
  e: "é",
  i: "í",
  o: "ó",
  u: "ú",
  y: "ý",
  A: "Á",
  E: "É",
  I: "Í",
  O: "Ó",
  U: "Ú",
  Y: "Ý",
};

/**
 * Development-only pseudo-locale: accents every Latin vowel, wraps the string and
 * adds padding so clipping and expansion bugs show up in screenshots. Placeholders
 * are left untouched.
 */
function pseudoText(value: string): string {
  const transformed = value
    .split(/(\{\w+\})/g)
    .map((part) => (part.startsWith("{") ? part : [...part].map((char) => PSEUDO_MAP[char] ?? char).join("")))
    .join("");
  return `⟦${transformed} ~ ${"·".repeat(Math.max(1, Math.ceil(value.length / 12)))}⟧`;
}

const pseudoMessages = Object.fromEntries(
  Object.entries(messages.en).map(([key, value]) => [key, pseudoText(value)]),
) as Record<MessageKey, string>;

const allMessages = { ...messages, pseudo: pseudoMessages } as const;

export function t(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const localeMessages: Record<string, string> = allMessages[locale] ?? allMessages.en;
  const template = localeMessages[key] ?? allMessages.en[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "vi";
}
